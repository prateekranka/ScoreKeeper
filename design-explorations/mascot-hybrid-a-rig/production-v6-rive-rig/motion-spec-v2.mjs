export function validateMotionSpec() {
  const errors = [];
  for (const performance of PERFORMANCES) {
    for (const [node, properties] of Object.entries(performance.tracks)) {
      if (!PIVOTS[node]) errors.push(`${performance.slug}: unknown node ${node}`);
      for (const [property, keys] of Object.entries(properties)) {
        if (!keys.length || keys[0][0] !== 0 || keys.at(-1)[0] !== performance.durationFrames) {
          errors.push(`${performance.slug}/${node}/${property}: missing endpoints`);
        }
        for (let index = 1; index < keys.length; index += 1) {
          if (keys[index][0] <= keys[index - 1][0]) errors.push(`${performance.slug}/${node}/${property}: frames not increasing`);
        }
        if (performance.loop && keys[0][1] !== keys.at(-1)[1]) errors.push(`${performance.slug}/${node}/${property}: loop mismatch`);
      }
    }
  }
  if (errors.length) throw new Error(errors.join("\n"));
  return { performances: PERFORMANCES.length, nodes: Object.keys(PIVOTS).length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(`${JSON.stringify(validateMotionSpec(), null, 2)}\n`);
}
